    private const val PREFS_NAME = "daily_quote_prefs"
    private const val KEY_DATE = "last_show_date"
    private const val KEY_QUOTE_INDEX = "last_quote_index"

    fun getDailyQuote(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val today = SimpleDateFormat("yyyyMMdd", Locale.getDefault()).format(Date())
        val lastDate = prefs.getString(KEY_DATE, "")
        val lastIndex = prefs.getInt(KEY_QUOTE_INDEX, -1)

        return if (today == lastDate && lastIndex >= 0) {
            quotes[lastIndex]
        } else {
            val newIndex = java.util.Random().nextInt(quotes.size)
            prefs.edit()
                .putString(KEY_DATE, today)
                .putInt(KEY_QUOTE_INDEX, newIndex)
                .apply()
            quotes[newIndex]
        }
    }
